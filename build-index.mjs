#!/usr/bin/env node
// build-index.mjs — Scrapbox (Cosense) プロジェクトの全ページタイトルを取得し、
// 辞書順に並べて pages.js を書き出す。index.html はこの pages.js だけを読む。
//
//   node build-index.mjs [project] [out]      (default: nostr pages.js)
//
//   env SCRAPBOX_SID : connect.sid cookie の値。private プロジェクトのときだけ必要。
//                      pages.js には書き込まれない。
//
// 漢字タイトルの読みは mecab (-Oyomi) があれば使う。無ければコードポイント順。
// 読みの誤りは yomi.tsv (タイトル<TAB>よみ) で上書きできる。

import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';

const project = process.argv[2] || 'nostr';
const out = process.argv[3] || 'pages.js';
const sid = process.env.SCRAPBOX_SID;
const headers = sid ? { cookie: `connect.sid=${sid}` } : {};

async function fetchTitles() {
  const titles = [];
  for (let skip = 0; ;) {
    const url = `https://scrapbox.io/api/pages/${encodeURIComponent(project)}?limit=1000&skip=${skip}`;
    const res = await fetch(url, { headers });
    if (!res.ok) throw new Error(`${res.status} ${res.statusText}: ${url}`);
    const j = await res.json();
    for (const p of j.pages) titles.push(p.title);
    skip += j.pages.length;
    if (j.pages.length === 0 || skip >= j.count) break;
  }
  return titles;
}

const HAN = /\p{Script=Han}/u;

function readings(titles) {
  const map = new Map();
  const need = titles.filter(t => HAN.test(t));
  if (need.length) {
    const r = spawnSync('mecab', ['-Oyomi'], { input: need.join('\n') + '\n', encoding: 'utf8' });
    const lines = r.status === 0 ? r.stdout.split('\n') : [];
    if (lines.length >= need.length) need.forEach((t, i) => map.set(t, lines[i]));
    else console.warn('mecab が使えないため、漢字タイトルはコードポイント順になります');
  }
  if (existsSync('yomi.tsv')) {
    for (const line of readFileSync('yomi.tsv', 'utf8').split('\n')) {
      const [t, y] = line.split('\t');
      if (t && y && !t.startsWith('#')) map.set(t, y.trim());
    }
  }
  return map;
}

const kata2hira = s => s.replace(/[ァ-ヶ]/g, c => String.fromCharCode(c.charCodeAt(0) - 0x60));

function sortKey(title, yomi) {
  let s = (yomi ?? title).normalize('NFKC');
  s = s.replace(/^(?:\s*(?:【[^】]*】|［[^］]*］|\[[^\]]*\]))+/u, '');   // 【完了】 等の接頭タグは無視
  s = kata2hira(s).toLowerCase().replace(/[^\p{L}\p{N}]/gu, '');
  return s || title.toLowerCase();
}

const LATIN = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';
const GYOU = 'あかさたなはまやらわ';
const KANA_ROWS = ['あいうえおぁぃぅぇぉゔ', 'かきくけこゕゖ', 'さしすせそ', 'たちつてとっ', 'なにぬねの',
  'はひふへほ', 'まみむめも', 'やゆよゃゅょ', 'らりるれろ', 'わゐゑをんゎ'];
const SECTIONS = ['#', ...LATIN, ...GYOU, '漢'];

function sectionOf(key) {
  const c = key.normalize('NFD').replace(/\p{M}/gu, '')[0] || '';
  if (/[a-z]/.test(c)) return c.toUpperCase();
  const r = KANA_ROWS.findIndex(row => row.includes(c));
  if (r >= 0) return GYOU[r];
  if (HAN.test(c)) return '漢';
  return '#';
}

const titles = await fetchTitles();
const yomi = readings(titles);
const coll = new Intl.Collator('ja', { numeric: true });
const entries = titles.map(title => {
  const key = sortKey(title, yomi.get(title));
  return { title, key, sec: SECTIONS.indexOf(sectionOf(key)) };
});
entries.sort((a, b) => a.sec - b.sec || coll.compare(a.key, b.key) || coll.compare(a.title, b.title));

const sections = [];
entries.forEach((e, i) => {
  if (!sections.length || sections[sections.length - 1][0] !== SECTIONS[e.sec]) sections.push([SECTIONS[e.sec], i]);
});

const data = {
  project,
  built: new Date().toISOString(),
  titles: entries.map(e => e.title),
  keys: entries.map(e => e.key),
  sections,
};
writeFileSync(out, `/* generated by build-index.mjs — do not edit */\nwindow.THUMB_INDEX = ${JSON.stringify(data)};\n`);
console.log(`${out}: ${entries.length} pages, ${sections.length} sections`);
console.log(sections.map(([l, s], k) => `${l}:${(sections[k + 1]?.[1] ?? entries.length) - s}`).join(' '));
